-- V1 (versao segura): tabelas no schema "seguro".
-- Os dados sao semeados por codigo (DataSeeder) com as senhas ja em hash BCrypt.

CREATE TABLE usuarios (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(255),
    email   VARCHAR(255) UNIQUE,
    senha   VARCHAR(255),   -- guarda o HASH BCrypt, nunca a senha em texto
    perfil  VARCHAR(50)
);

CREATE TABLE consultas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id   BIGINT NOT NULL REFERENCES usuarios(id),
    nome_paciente VARCHAR(255),
    data          VARCHAR(255),
    procedimento  VARCHAR(255),
    dentista      VARCHAR(255),
    observacoes   VARCHAR(1000),
    estado        VARCHAR(50)
);
