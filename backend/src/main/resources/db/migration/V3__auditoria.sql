-- V3: AUDITORIA ao nivel da BASE DE DADOS (triggers).
--
-- Regista TODAS as alteracoes (INSERT/UPDATE/DELETE) em consultas e usuarios,
-- venham de onde vierem -- incluindo de um ataque -- porque o registo acontece
-- no PostgreSQL, por baixo da aplicacao. A app nao consegue contornar isto.
--
-- Idempotente (pode correr mais do que uma vez sem erro).

CREATE TABLE IF NOT EXISTS auditoria (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    momento       TIMESTAMPTZ NOT NULL DEFAULT now(),
    operacao      VARCHAR(10),            -- INSERT / UPDATE / DELETE
    tabela        VARCHAR(63),
    registo_id    BIGINT,
    utilizador_bd VARCHAR(100),           -- utilizador da ligacao a BD
    ip_cliente    INET,                   -- IP da ligacao (o servidor da app)
    dados_antigos JSONB,                  -- estado anterior (UPDATE/DELETE)
    dados_novos   JSONB                   -- estado novo (INSERT/UPDATE)
);

CREATE OR REPLACE FUNCTION fn_auditoria() RETURNS trigger AS $$
BEGIN
    INSERT INTO auditoria (operacao, tabela, registo_id, utilizador_bd, ip_cliente, dados_antigos, dados_novos)
    VALUES (
        TG_OP,
        TG_TABLE_NAME,
        COALESCE(NEW.id, OLD.id),
        session_user,
        inet_client_addr(),
        CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) END,
        CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) END
    );
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_aud_consultas ON consultas;
CREATE TRIGGER trg_aud_consultas
    AFTER INSERT OR UPDATE OR DELETE ON consultas
    FOR EACH ROW EXECUTE FUNCTION fn_auditoria();

DROP TRIGGER IF EXISTS trg_aud_usuarios ON usuarios;
CREATE TRIGGER trg_aud_usuarios
    AFTER INSERT OR UPDATE OR DELETE ON usuarios
    FOR EACH ROW EXECUTE FUNCTION fn_auditoria();
